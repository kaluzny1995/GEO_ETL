class TestModelContract:
    @pytest.mark.parametrize("model_cls, kwargs, expected", VALID_CASES)
    def test_valid_row(self, model_cls, kwargs, expected):
        # Act
        row = model_cls(**kwargs)
        # Assert
        for field, value in expected.items():
            assert getattr(row, field) == value

    @pytest.mark.parametrize("model_cls, kwargs, none_fields", OPTIONAL_CASES)
    def test_optional_fields_none(self, model_cls, kwargs, none_fields):
        # Act
        row = model_cls(**kwargs)
        # Assert
        for field in none_fields:
            assert getattr(row, field) is None

    @pytest.mark.parametrize("model_cls, count", COUNT_CASES)
    def test_schema_field_count(self, model_cls, count):
        # Act
        schema = pydantic_to_spark_schema(model_cls)
        # Assert
        assert len(schema.fields) == count

    @pytest.mark.parametrize("model_cls, kwargs", FILE_DATE_CASES)
    def test_missing_file_date_raises(self, model_cls, kwargs):
        # Assert
        with pytest.raises(ValidationError):
            model_cls(**kwargs)

    @pytest.mark.parametrize("model_cls, expected_names", NAMES_CASES)
    def test_schema_field_names(self, model_cls, expected_names):
        # Act
        schema = pydantic_to_spark_schema(model_cls)
        # Assert
        assert [field.name for field in schema.fields] == expected_names

    @pytest.mark.parametrize("model_cls, expected_nullable", NULLABLE_CASES)
    def test_nullable_fields(self, model_cls, expected_nullable):
        # Act
        schema = pydantic_to_spark_schema(model_cls)
        # Assert
        nullable = {field.name for field in schema.fields if field.nullable}
        assert nullable == expected_nullable

    @pytest.mark.parametrize("model_cls, names, spark_type", TYPE_CASES)
    def test_field_types(self, model_cls, names, spark_type):
        # Act
        schema = pydantic_to_spark_schema(model_cls)
        # Assert
        for name in names:
            field = next(f for f in schema.fields if f.name == name)
            assert isinstance(field.dataType, spark_type), name
